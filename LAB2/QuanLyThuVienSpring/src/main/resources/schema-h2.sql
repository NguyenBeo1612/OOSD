-- Schema H2 (chỉ dùng cho profile demo/test). CSDL thật: database/QuanLyThuVien.sql (SQL Server).
DROP TABLE IF EXISTS TaiKhoan;
DROP TABLE IF EXISTS PhieuPhat;
DROP TABLE IF EXISTS ChiTietPhieuMuon;
DROP TABLE IF EXISTS PhieuMuon;
DROP TABLE IF EXISTS TheDocGia;
DROP TABLE IF EXISTS DocGia;
DROP TABLE IF EXISTS DauSach;
DROP TABLE IF EXISTS NhaXuatBan;
DROP TABLE IF EXISTS TheLoai;
DROP TABLE IF EXISTS NhanVien;

CREATE TABLE NhanVien (
    MaNhanVien NVARCHAR(20) NOT NULL PRIMARY KEY,
    Ho NVARCHAR(50) NOT NULL,
    Ten NVARCHAR(50) NOT NULL,
    Phai NVARCHAR(10) NOT NULL,
    NgaySinh DATE NOT NULL,
    ChucVu NVARCHAR(80) NOT NULL,
    SoDienThoai NVARCHAR(20)
);
CREATE TABLE TheLoai (
    MaTheLoai NVARCHAR(20) NOT NULL PRIMARY KEY,
    TenTheLoai NVARCHAR(100) NOT NULL UNIQUE
);
CREATE TABLE NhaXuatBan (
    MaNhaXuatBan NVARCHAR(20) NOT NULL PRIMARY KEY,
    DiaChi NVARCHAR(250),
    SoDienThoai NVARCHAR(20)
);
CREATE TABLE DauSach (
    MaDauSach NVARCHAR(20) NOT NULL PRIMARY KEY,
    TenSach NVARCHAR(200) NOT NULL,
    NamXuatBan INT NOT NULL,
    SoLuongHienCo INT NOT NULL CHECK (SoLuongHienCo >= 0),
    MaTheLoai NVARCHAR(20) NOT NULL REFERENCES TheLoai(MaTheLoai),
    MaNhaXuatBan NVARCHAR(20) NOT NULL REFERENCES NhaXuatBan(MaNhaXuatBan)
);
CREATE TABLE DocGia (
    MaDocGia NVARCHAR(20) NOT NULL PRIMARY KEY,
    Ho NVARCHAR(50) NOT NULL,
    Ten NVARCHAR(50) NOT NULL,
    NgaySinh DATE NOT NULL,
    Phai NVARCHAR(10) NOT NULL,
    SoDienThoai NVARCHAR(20),
    DiaChi NVARCHAR(250) NOT NULL,
    Email NVARCHAR(150) NOT NULL,
    Anh3x4 NVARCHAR(260)
);
CREATE TABLE TheDocGia (
    MaThe NVARCHAR(30) NOT NULL PRIMARY KEY,
    MaDocGia NVARCHAR(20) NOT NULL REFERENCES DocGia(MaDocGia),
    NgayCap DATE NOT NULL,
    HanSuDung DATE NOT NULL,
    DaDongLePhi BIT NOT NULL,
    TrangThai BIT DEFAULT 1 NOT NULL,
    CHECK (HanSuDung >= NgayCap)
);
CREATE TABLE PhieuMuon (
    MaPhieuMuon NVARCHAR(30) NOT NULL PRIMARY KEY,
    MaDocGia NVARCHAR(20) NOT NULL REFERENCES DocGia(MaDocGia),
    MaNhanVien NVARCHAR(20) NOT NULL REFERENCES NhanVien(MaNhanVien),
    NgayMuon DATE NOT NULL,
    NgayHenTra DATE NOT NULL,
    CHECK (NgayHenTra >= NgayMuon)
);
CREATE TABLE ChiTietPhieuMuon (
    MaChiTiet NVARCHAR(35) NOT NULL PRIMARY KEY,
    MaPhieuMuon NVARCHAR(30) NOT NULL REFERENCES PhieuMuon(MaPhieuMuon),
    MaDauSach NVARCHAR(20) NOT NULL REFERENCES DauSach(MaDauSach),
    NgayTraThucTe DATE,
    TinhTrangTra NVARCHAR(50),
    UNIQUE (MaPhieuMuon, MaDauSach)
);
CREATE TABLE PhieuPhat (
    MaPhieuPhat NVARCHAR(35) NOT NULL PRIMARY KEY,
    MaChiTiet NVARCHAR(35) NOT NULL REFERENCES ChiTietPhieuMuon(MaChiTiet),
    MaNhanVien NVARCHAR(20) NOT NULL REFERENCES NhanVien(MaNhanVien),
    NgayPhat DATE NOT NULL,
    LyDo NVARCHAR(250) NOT NULL,
    PhiPhat DECIMAL(18,0) NOT NULL CHECK (PhiPhat >= 0)
);
CREATE TABLE TaiKhoan (
    TenDangNhap NVARCHAR(50) NOT NULL PRIMARY KEY,
    MatKhau NVARCHAR(100) NOT NULL,
    MaNhanVien NVARCHAR(20) NOT NULL UNIQUE REFERENCES NhanVien(MaNhanVien),
    VaiTro NVARCHAR(20) NOT NULL CHECK (VaiTro IN ('THU_THU', 'QL_SACH')),
    HoatDong BIT DEFAULT 1 NOT NULL
);
